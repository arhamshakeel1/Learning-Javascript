// ===========================================================
//           MOST USED JAVASCRIPT METHODS CHEAT SHEET
// ===========================================================

// ======================= DOM SELECTORS =======================

// querySelector()          -> Selects the first matching HTML element.
// querySelectorAll()       -> Selects all matching HTML elements (NodeList).
// getElementById()         -> Selects an element using its unique id.


// ======================= DOM CONTENT =======================

// textContent              -> Gets/Sets the text inside an element.
// innerText                -> Gets/Sets only the visible text.
// innerHTML                -> Gets/Sets HTML content inside an element.


// ======================= DOM STYLING =======================

// style                    -> Changes an element's CSS using JavaScript.


// ======================= CLASS METHODS =======================

// classList.add()          -> Adds a CSS class.
// classList.remove()       -> Removes a CSS class.
// classList.toggle()       -> Adds if missing, removes if present.
// classList.contains()     -> Checks if a class exists.


// ======================= ATTRIBUTES =======================

// getAttribute()           -> Gets an attribute's value.
// setAttribute()           -> Creates or updates an attribute.
// removeAttribute()        -> Removes an attribute.


// ======================= CREATE / REMOVE =======================

// createElement()          -> Creates a new HTML element in memory.
// appendChild()            -> Adds an element as the last child.
// append()                 -> Adds elements or text at the end.
// prepend()                -> Adds an element as the first child.
// remove()                 -> Removes an element from the DOM.


// ======================= DOM TRAVERSAL =======================

// children                 -> Returns all child elements (HTMLCollection).
// parentElement            -> Returns the parent element.
// firstElementChild        -> Returns the first child element.
// lastElementChild         -> Returns the last child element.


// ======================= ARRAY METHODS =======================

// push()                   -> Adds an element to the end of an array.
// pop()                    -> Removes the last element.
// shift()                  -> Removes the first element.
// unshift()                -> Adds an element to the beginning.

// includes()               -> Checks if an array contains a value.
// indexOf()                -> Returns the index of a value.

// forEach()                -> Loops through every array element.
// map()                    -> Creates a new transformed array.
// filter()                 -> Creates a new array with matching elements.
// reduce()                 -> Combines all values into one result.

// slice()                  -> Returns part of an array without changing it.
// splice()                 -> Adds/Removes elements by modifying the array.
// join()                   -> Converts an array into a string.
// sort()                   -> Sorts an array.
// reverse()                -> Reverses the order of an array.
// Array.from()             -> Converts iterable objects into arrays.


// ======================= STRING METHODS =======================

// length                   -> Returns the number of characters.
// trim()                   -> Removes spaces from both ends.
// toUpperCase()            -> Converts text to uppercase.
// toLowerCase()            -> Converts text to lowercase.
// includes()               -> Checks if a string contains text.
// replace()                -> Replaces part of a string.
// split()                  -> Converts a string into an array.
// slice()                  -> Returns part of a string.


// ======================= MATH METHODS =======================

// Math.random()            -> Generates a random decimal number.
// Math.floor()             -> Rounds down.
// Math.ceil()              -> Rounds up.
// Math.round()             -> Rounds to the nearest integer.
// Math.max()               -> Returns the largest value.
// Math.min()               -> Returns the smallest value.
// Math.abs()               -> Returns the positive value.
// Math.pow()               -> Raises a number to a power.


// ======================= OBJECT METHODS =======================

// Object.keys()            -> Returns all object keys.
// Object.values()          -> Returns all object values.
// Object.entries()         -> Returns key-value pairs as arrays.


// ======================= TYPE CONVERSION =======================

// Number()                 -> Converts a value into a number.
// String()                 -> Converts a value into a string.
// Boolean()                -> Converts a value into true or false.


// ======================= FUNCTIONS =======================

// return                   -> Sends a value back from a function.
// =>                       -> Creates an arrow function.


// ======================= LOOPS =======================

// for                      -> Repeats code a fixed number of times.
// for...of                 -> Loops through values of iterable objects.
// for...in                 -> Loops through object keys.
// forEach()                -> Loops through arrays and NodeLists.


// ======================= CONDITIONS =======================

// if                       -> Executes code when a condition is true.
// else                     -> Executes when the condition is false.
// switch                   -> Chooses one case from many options.
// ? :                      -> Short form of if...else (Ternary Operator).


// ======================= CONSOLE =======================

// console.log()            -> Prints values for debugging.
// console.table()          -> Displays data in a table.
// console.error()          -> Displays error messages.


// ======================= TIMERS =======================

// setTimeout()             -> Runs code once after a delay.
// setInterval()            -> Runs code repeatedly after a delay.
// clearTimeout()           -> Cancels a timeout.
// clearInterval()          -> Stops an interval.


// ======================= EVENTS =======================

// addEventListener()       -> Runs a function when an event occurs.

// click                    -> Triggered when an element is clicked.
// input                    -> Triggered when input value changes.
// submit                   -> Triggered when a form is submitted.
// keydown                  -> Triggered when a key is pressed.
// keyup                    -> Triggered when a key is released.
// change                   -> Triggered when an input loses focus after changing.


